//! The EVM pool's generated parts, from the same parameters and keys the
//! Solana program uses (DECISIONS §158):
//!
//!   cargo run --release -p zyn-pool --bin zyn-pool-sol -- <contracts dir>
//!
//! Writes `src/pool/PoseidonT3.sol` (circom's Poseidon of two inputs, straight
//! assembly), `src/pool/ZynPoolVerifier.sol` (Groth16 over the precompiles,
//! the testnet key's constants) and `test/fixtures/pool.json` (hash vectors, a
//! tree, and real proofs for both kinds of spend, for the Foundry tests).

use ark_bn254::Fr;
use ark_ff::{BigInteger, PrimeField};
use light_poseidon::parameters::bn254_x5::get_poseidon_parameters;
use serde_json::json;
use zyn_pool::circuit::Spend;
use zyn_pool::export::{ProofBytes, VkBytes};
use zyn_pool::tree::{zeros, Tree};
use zyn_pool::{binding_to_address, binding_to_zyn, fr_be, keys, poseidon, Note, DEPTH};

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn lit(x: Fr) -> String {
    format!("0x{}", hex(&x.into_bigint().to_bytes_be()))
}

fn word(b: &[u8]) -> String {
    format!("0x{}", hex(b))
}

fn poseidon_sol() -> String {
    let p = get_poseidon_parameters::<Fr>(3).expect("t = 3");
    let mut body = String::new();
    let half = p.full_rounds / 2;
    let rounds = p.full_rounds + p.partial_rounds;
    for r in 0..rounds {
        for i in 0..3 {
            body += &format!("      s{i} := addmod(s{i}, {}, F)\n", lit(p.ark[r * 3 + i]));
        }
        let full = r < half || r >= half + p.partial_rounds;
        for i in 0..if full { 3 } else { 1 } {
            body += &format!("      t := mulmod(s{i}, s{i}, F)\n      t := mulmod(t, t, F)\n      s{i} := mulmod(s{i}, t, F)\n");
        }
        // The MDS matrix is the same every round: read from memory, where
        // it is written once, rather than inlined 65 times (which would not
        // fit the EVM's 24 KB code limit).
        for i in 0..3 {
            body += &format!(
                "      n{i} := addmod(addmod(mulmod(s0, mload(add(m, {})), F), mulmod(s1, mload(add(m, {})), F), F), mulmod(s2, mload(add(m, {})), F), F)\n",
                32 * (3 * i),
                32 * (3 * i + 1),
                32 * (3 * i + 2)
            );
        }
        body += "      s0 := n0\n      s1 := n1\n      s2 := n2\n";
    }
    format!(
        r#"// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// Generated by `zyn-pool-sol` (zyn-pool). Do not edit.
//
// Circom's Poseidon of two inputs (BN254, x^5, 8 full and {pr} partial rounds,
// state [0, a, b], output the first element): the hash the zyn-pool circuit,
// Solana's Poseidon syscall and this contract share, so a tree built on any
// of them has the same root.
library PoseidonT3 {{
  /// `a` and `b` must be field elements (below the BN254 scalar field).
  function hash(uint256 a, uint256 b) internal pure returns (uint256 r) {{
    assembly {{
      let F := 21888242871839275222246405745257275088548364400416034343698204186575808495617
      // The MDS matrix, row by row, in scratch memory past the free pointer
      // (nothing is allocated while this runs).
      let m := mload(0x40)
{mds}      let s0 := 0
      let s1 := a
      let s2 := b
      let t := 0
      let n0 := 0
      let n1 := 0
      let n2 := 0
{body}      r := s0
    }}
  }}
}}
"#,
        pr = p.partial_rounds,
        mds = (0..9).map(|k| format!("      mstore(add(m, {}), {})\n", 32 * k, lit(p.mds[k / 3][k % 3]))).collect::<String>(),
    )
}

fn verifier_sol(v: &VkBytes) -> String {
    let g1 = |p: &[u8; 64]| format!("{}, {}", word(&p[..32]), word(&p[32..]));
    let g2 = |p: &[u8; 128]| format!("{}, {}, {}, {}", word(&p[..32]), word(&p[32..64]), word(&p[64..96]), word(&p[96..]));
    let ic = v.ic.iter().enumerate().map(|(i, p)| format!("  uint256 constant IC{i}X = {};\n  uint256 constant IC{i}Y = {};\n", word(&p[..32]), word(&p[32..]))).collect::<String>();
    format!(
        r#"// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// Generated by `zyn-pool-sol` (zyn-pool). Do not edit.
//
// Groth16 over BN254 for the zyn-pool spend circuit, on the EVM's precompiles
// (0x06 add, 0x07 mul, 0x08 pairing). Proofs are the bytes the Solana program
// takes: A negated, B, C, EIP-197 layout — one proof format for both chains.
//
// TESTNET KEY: a one-party setup with a public seed (DECISIONS §158.8).
abstract contract ZynPoolVerifier {{
  uint256 internal constant Q = 21888242871839275222246405745257275088696311157297823662689037894645226208583;
  uint256 internal constant R = 21888242871839275222246405745257275088548364400416034343698204186575808495617;

  // alpha (G1), beta, gamma, delta (G2: x.c1, x.c0, y.c1, y.c0)
  uint256[2] internal ALPHA = [{alpha}];
  uint256[4] internal BETA = [{beta}];
  uint256[4] internal GAMMA = [{gamma}];
  uint256[4] internal DELTA = [{delta}];
{ic}
  /// `proof` is 256 bytes (A negated, B, C); `input` the root, the nullifier
  /// hash and the binding, each below R.
  function verifyProof(bytes calldata proof, uint256[3] memory input) internal view returns (bool) {{
    if (proof.length != 256) return false;
    for (uint256 i = 0; i < 3; i++) {{
      if (input[i] >= R) return false;
    }}
    // vk_x = IC0 + sum(input[i] * IC[i+1])
    uint256[2] memory x = [IC0X, IC0Y];
    x = _add(x, _mul([IC1X, IC1Y], input[0]));
    x = _add(x, _mul([IC2X, IC2Y], input[1]));
    x = _add(x, _mul([IC3X, IC3Y], input[2]));
    uint256[24] memory p;
    // e(-A, B)
    for (uint256 i = 0; i < 6; i++) {{
      p[i] = uint256(bytes32(proof[32 * i:32 * (i + 1)]));
    }}
    // e(vk_x, gamma)
    p[6] = x[0];
    p[7] = x[1];
    for (uint256 i = 0; i < 4; i++) p[8 + i] = GAMMA[i];
    // e(C, delta)
    p[12] = uint256(bytes32(proof[192:224]));
    p[13] = uint256(bytes32(proof[224:256]));
    for (uint256 i = 0; i < 4; i++) p[14 + i] = DELTA[i];
    // e(alpha, beta)
    p[18] = ALPHA[0];
    p[19] = ALPHA[1];
    for (uint256 i = 0; i < 4; i++) p[20 + i] = BETA[i];
    uint256[1] memory out;
    bool ok;
    assembly {{
      ok := staticcall(gas(), 0x08, p, 768, out, 32)
    }}
    return ok && out[0] == 1;
  }}

  function _add(uint256[2] memory a, uint256[2] memory b) private view returns (uint256[2] memory r) {{
    uint256[4] memory i = [a[0], a[1], b[0], b[1]];
    bool ok;
    assembly {{
      ok := staticcall(gas(), 0x06, i, 128, r, 64)
    }}
    require(ok, "ec add");
  }}

  function _mul(uint256[2] memory a, uint256 s) private view returns (uint256[2] memory r) {{
    uint256[3] memory i = [a[0], a[1], s];
    bool ok;
    assembly {{
      ok := staticcall(gas(), 0x07, i, 96, r, 64)
    }}
    require(ok, "ec mul");
  }}
}}
"#,
        alpha = g1(&v.alpha_g1),
        beta = g2(&v.beta_g2),
        gamma = g2(&v.gamma_g2),
        delta = g2(&v.delta_g2),
    )
}

fn main() {
    let dir = std::path::PathBuf::from(std::env::args().nth(1).expect("the contracts directory"));
    std::fs::create_dir_all(dir.join("src/pool")).unwrap();
    std::fs::create_dir_all(dir.join("test/fixtures")).unwrap();
    let (pk, vk) = keys::setup(keys::testnet_seed());
    let v = VkBytes::of(&vk);
    assert_eq!(v.ic.len(), 4, "three public inputs");
    std::fs::write(dir.join("src/pool/PoseidonT3.sol"), poseidon_sol()).unwrap();
    std::fs::write(dir.join("src/pool/ZynPoolVerifier.sol"), verifier_sol(&v)).unwrap();

    // Fixtures: hash vectors, a tree of three notes, and proofs for the
    // second note, one into Zyn and one to an address.
    let a = Fr::from(1u64);
    let b = Fr::from(2u64);
    let notes: Vec<Note> = (1u8..=3).map(|i| Note::from_seed(&[i; 64])).collect();
    let mut tree = Tree::default();
    for n in &notes {
        tree.insert(n.commitment());
    }
    let mine = &notes[1];
    let code = [0x42u8; 32];
    let recipient = [0x11u8; 20];
    let relayer = [0x22u8; 20];
    let fee = 1_000_000_000_000_000u64; // 0.001 ETH
    let spend = |binding: Fr, seed: u8| {
        let s = Spend { root: tree.root(), nullifier_hash: mine.nullifier_hash(), binding, nullifier: mine.nullifier, secret: mine.secret, path: tree.path(1) };
        let proof = keys::prove(&pk, s.clone(), [seed; 32]).unwrap();
        assert!(keys::verify(&vk, &s.public_inputs(), &proof));
        hex(&ProofBytes::of(&proof).to_bytes())
    };
    let fixtures = json!({
        "poseidon": { "a": word(&fr_be(a)), "b": word(&fr_be(b)), "out": word(&fr_be(poseidon(&[a, b]))) },
        "zeros": zeros().iter().map(|z| word(&fr_be(*z))).collect::<Vec<_>>(),
        "commitments": notes.iter().map(|n| word(&fr_be(n.commitment()))).collect::<Vec<_>>(),
        "root": word(&fr_be(tree.root())),
        "nullifierHash": word(&fr_be(mine.nullifier_hash())),
        "code": word(&code),
        "toZynProof": format!("0x{}", spend(binding_to_zyn(&code), 5)),
        "recipient": word(&recipient),
        "relayer": word(&relayer),
        "fee": fee,
        "toAddressProof": format!("0x{}", spend(binding_to_address(&recipient, &relayer, fee), 6)),
        "depth": DEPTH,
    });
    std::fs::write(dir.join("test/fixtures/pool.json"), serde_json::to_string_pretty(&fixtures).unwrap()).unwrap();
    println!("wrote src/pool/PoseidonT3.sol, src/pool/ZynPoolVerifier.sol, test/fixtures/pool.json");
}
