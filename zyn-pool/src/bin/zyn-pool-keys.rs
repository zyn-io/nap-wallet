//! Testnet keys for the spend circuit, and the constants the pools embed.
//!
//!   cargo run --release -p zyn-pool --bin zyn-pool-keys -- <out dir>
//!
//! Writes `spend.pk` and `spend.vk` (arkworks, compressed), `spend.pk.raw`
//! (uncompressed, for the browser), `vk.rs` (the
//! Solana program's verifying key) and `zeros.rs` (empty-subtree roots).
//!
//! The setup is ONE PARTY with a PUBLIC seed: anyone can forge proofs under
//! these keys. They exist so testnet runs end to end; mainnet keys come from a
//! ceremony (DECISIONS §158.8).

use ark_serialize::CanonicalSerialize;
use zyn_pool::export::VkBytes;
use zyn_pool::{fr_be, keys, tree, DEPTH};

fn main() {
    let out = std::path::PathBuf::from(std::env::args().nth(1).expect("an output directory"));
    std::fs::create_dir_all(&out).expect("output directory");
    let (pk, vk) = keys::setup(keys::testnet_seed());

    let mut b = Vec::new();
    pk.serialize_compressed(&mut b).expect("pk");
    std::fs::write(out.join("spend.pk"), &b).expect("write pk");
    // The same key uncompressed, for the browser: loading it skips
    // decompressing every point (`nap-pool`'s `load_key`).
    let mut b = Vec::new();
    pk.serialize_uncompressed(&mut b).expect("pk raw");
    std::fs::write(out.join("spend.pk.raw"), &b).expect("write pk raw");
    let mut b = Vec::new();
    vk.serialize_compressed(&mut b).expect("vk");
    std::fs::write(out.join("spend.vk"), &b).expect("write vk");

    let header = "// Generated by `zyn-pool-keys`. TESTNET ONLY: a one-party setup with a public seed.\n";
    std::fs::write(out.join("vk.rs"), format!("{header}{}", VkBytes::of(&vk).to_rust("SPEND_VK"))).expect("write vk.rs");

    let zeros = tree::zeros();
    let rows = zeros.iter().map(|z| format!("    {:?},", fr_be(*z))).collect::<Vec<_>>().join("\n");
    std::fs::write(
        out.join("zeros.rs"),
        format!("// Generated by `zyn-pool-keys`: the root of an empty subtree at each height.\npub const ZEROS: [[u8; 32]; {}] = [\n{rows}\n];\n", DEPTH + 1),
    )
    .expect("write zeros.rs");
    println!("keys and constants in {} (pk {} bytes)", out.display(), std::fs::metadata(out.join("spend.pk")).unwrap().len());
}
